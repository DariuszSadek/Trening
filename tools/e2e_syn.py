from playwright.sync_api import sync_playwright
OUT='/tmp/shots/'
errs=[]
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 393, 'height': 852}, device_scale_factor=2, is_mobile=True, has_touch=True)
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None); pg.on('dialog', lambda d: d.accept())
    pg.goto('http://localhost:8765/syn1/'); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+'s01_name.png')
    pg.fill('#nm', 'Tymek'); pg.click('#nm-ok'); pg.wait_for_timeout(400)
    pg.screenshot(path=OUT+'s02_home.png')
    pg.click('[data-start="A"]'); pg.wait_for_timeout(600)
    pg.fill('[data-plan="goblet"]', '12'); pg.wait_for_timeout(100)
    pg.locator('[data-block="0"]').scroll_into_view_if_needed(); pg.wait_for_timeout(500)
    pg.click('[data-done="0.0"]'); pg.wait_for_timeout(300)
    for k in ['0.1','0.2']:
        pg.fill(f'[data-k="reps"][data-key="{k}"]', '15'); pg.click(f'[data-done="{k}"]'); pg.wait_for_timeout(100)
    pg.wait_for_timeout(800)
    pg.screenshot(path=OUT+'s03_goblet.png')
    pg.click('[data-t="skip"]')
    pg.click('.ex-more[data-open="goblet"]'); pg.wait_for_timeout(800); pg.screenshot(path=OUT+'s04_dlg.png'); pg.click('[data-close]')
    pg.locator('[data-seq="cond"]').scroll_into_view_if_needed(); pg.wait_for_timeout(300); pg.screenshot(path=OUT+'s05_end.png')
    pg.click('[data-finish]'); pg.wait_for_timeout(500)
    pg.goto('http://localhost:8765/syn1/#/'); pg.wait_for_timeout(300)
    nxt = pg.get_attribute('.day-card.next', 'data-start')
    pg.click('[data-start="B"]'); pg.wait_for_timeout(600)
    pg.locator('[data-block="1"]').scroll_into_view_if_needed(); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+'s06_B.png')
    pg.locator('[data-block="F"]').scroll_into_view_if_needed(); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+'s07_farmer.png')
    pg.click('[data-finish]'); pg.wait_for_timeout(300)
    pg.goto('http://localhost:8765/syn1/#/'); pg.click('[data-start="A"]'); pg.wait_for_timeout(500)
    planA = pg.evaluate("JSON.parse(localStorage.getItem('trening.syn1.v1')).current.plan")
    # druga aplikacja – osobne dane
    pg.goto('http://localhost:8765/syn2/'); pg.wait_for_timeout(500)
    name2 = pg.is_visible('#nm')
    pg.screenshot(path=OUT+'s08_syn2.png')
    keys = pg.evaluate("Object.keys(localStorage)")
    # aplikacja taty – nienaruszona
    pg.goto('http://localhost:8765/'); pg.wait_for_timeout(400)
    dad = pg.inner_text('h1')
    print('następny po A:', nxt, '| plan A po 2×15 w F1:', planA, '| syn2 pyta o imię:', name2, '| klucze:', keys, '| tata:', dad)
    b.close()
print(errs or 'brak błędów')
